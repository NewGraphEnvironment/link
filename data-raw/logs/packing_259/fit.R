#!/usr/bin/env Rscript
# fit.R — how well each packing weight and host-speed setting predicted the
# 2026-10-23 provincial run's model legs, fitted on the 2026-10-17 run (link#259).
#
# Inputs, both beside this script:
#   log_rows.tsv  finished `log` rows of the two provincial `default` builds,
#                 exported from the dispatcher's database (README.md says how)
#   segments.tsv  FWA stream segments per watershed group (fwa_stream_networks_sp)
#
# Out of sample: every weight and speed is fitted on 2026-10-17 and scored on
# 2026-10-23's actual buckets (each group on the host its 10-23 log row names).
# A host's measured leg is the sum of its groups' logged minutes. Hosts are
# keyed by name, every cypher-job* pooled as `cloud` (operator, 2026-10-27).
#
# Usage: Rscript fit.R > fit.md   (from this directory)

r <- read.delim("log_rows.tsv", na.strings = "", colClasses = c(run_uid = "character"))
r <- r[!is.na(r$run_uid), ]                      # pre-run builds restored by #354
r$class <- ifelse(grepl("^cypher-", r$host), "cloud", r$host)
train <- r[r$run_uid == "20261017_004619-3f4c713b", ]
test  <- r[r$run_uid == "20261023_074321-24d85e8c", ]
seg <- read.delim("segments.tsv")
stopifnot(nrow(train) == 241, nrow(test) == 241,
          !anyDuplicated(train$wsg), !anyDuplicated(test$wsg),
          setequal(train$wsg, test$wsg), all(test$wsg %in% seg$wsg))
segs <- stats::setNames(seg$segments, seg$wsg)
# KTSU ran 65.4 min against 1.3 the week before, and OKAN's finished row is its
# re-model after the driver exited (its 4 h stall has no finished row).
stalls <- c("KTSU", "OKAN")

# --- host speeds fitted on 10-17 ------------------------------------------
# The calibration #163 prescribes, on whole legs: projected = the leg's weight
# at speed 1 (segments x the run's own min-per-segment rate, which is what the
# 10-17 run was packed on), actual = its logged minutes. A class's observed
# speed is projected / actual, summed over its legs, relative to m1's.
rate17 <- sum(train$minutes) / sum(segs[train$wsg])
leg_speed <- function(d, w) {
  p <- tapply(w, d$class, sum)
  a <- tapply(d$minutes, d$class, sum)
  s <- p / a
  s / s[["m1"]]
}
sp_obs <- leg_speed(train, segs[train$wsg] * rate17)
sp_damped <- 0.7 * 1 + 0.3 * sp_obs              # one #163 step from equal
sp_damped <- sp_damped / sp_damped[["m1"]]

# --- the same groups on both classes: speed read directly -------------------
both <- merge(train[, c("wsg", "class", "minutes")], test[, c("wsg", "class", "minutes")],
              by = "wsg", suffixes = c("17", "23"))
both <- both[!both$wsg %in% stalls, ]
drift <- function(c17, c23) {
  x <- both[both$class17 == c17 & both$class23 == c23, ]
  c(n = nrow(x), sum_ratio = sum(x$minutes23) / sum(x$minutes17))
}
cross <- rbind(`m1 -> m1` = drift("m1", "m1"), `cloud -> cloud` = drift("cloud", "cloud"),
               `m1 -> cloud` = drift("m1", "cloud"), `cloud -> m1` = drift("cloud", "m1"))

# --- weights per group (dispatcher-equivalent minutes at speed 1) -----------
m17 <- stats::setNames(train$minutes, train$wsg)
c17 <- stats::setNames(train$class, train$wsg)
weights <- list(segments = stats::setNames(as.vector(segs[test$wsg]) * rate17, test$wsg),
                minutes = m17[test$wsg],
                minutes_normalized = stats::setNames(as.vector(m17[test$wsg]) *
                                                       as.vector(sp_obs[c17[test$wsg]]), test$wsg))
speeds <- list(equal = c(m1 = 1, cloud = 1), learned = sp_obs, learned_damped = sp_damped)

score <- function(drop) {
  d <- test[!test$wsg %in% drop, ]
  meas <- tapply(d$minutes, d$host, sum)
  out <- list()
  for (wn in names(weights)) for (sn in names(speeds)) {
    w <- weights[[wn]][d$wsg]
    pred <- tapply(w / speeds[[sn]][d$class], d$host, sum)[names(meas)]
    err <- t(round(100 * (pred / meas - 1)))
    share <- round(100 * max(abs(pred / mean(pred) - meas / mean(meas))), 1)
    out[[length(out) + 1]] <- data.frame(weight = wn, speed = sn, err, share_err = share,
                                         makespan_pred = round(max(pred)),
                                         makespan_meas = round(max(meas)), check.names = FALSE)
  }
  list(meas = meas, tab = do.call(rbind, out))
}

md_table <- function(df) {
  cat("|", paste(names(df), collapse = " | "), "|\n")
  cat("|", paste(rep("---", ncol(df)), collapse = " | "), "|\n")
  for (i in seq_len(nrow(df))) cat("|", paste(df[i, ], collapse = " | "), "|\n")
  cat("\n")
}

cat("# Packing weights and host speeds, scored on the 2026-10-23 run (link#259)\n\n")
cat("Generated by `fit.R` from `log_rows.tsv` and `segments.tsv`. Fitted on 2026-10-17,",
    "scored on 2026-10-23's actual buckets.\n\n")
cat(sprintf(paste0("10-17 rate: %.3f min per 1000 FWA segments. Host speeds fitted on 10-17 legs ",
                   "(relative to m1): cloud %.3f (one damped step: %.3f).\n\n"),
            1000 * rate17, sp_obs[["cloud"]], sp_damped[["cloud"]]))
cat("## The same groups on both runs\n\n")
cat("Summed 10-23 minutes over summed 10-17 minutes for the groups each pair of classes ran (stalls left out).\n\n")
md_table(data.frame(classes = rownames(cross), n = cross[, "n"],
                    ratio = sprintf("%.3f", cross[, "sum_ratio"])))
for (drop in list(character(0), stalls)) {
  s <- score(drop)
  cat(sprintf("## Per-leg error, %%, predicted against measured (%s)\n\n",
              if (length(drop)) "KTSU and OKAN left out" else "as logged"))
  cat("Measured legs (min):", paste(sprintf("%s %.0f", names(s$meas), s$meas), collapse = ", "), "\n\n")
  cat("`share_err`: the largest gap, in points, between a leg's predicted and measured share of the mean leg.",
      "It is what packing balance depends on; the per-leg % also carries the run-wide drift.\n\n")
  md_table(s$tab)
}

# --- the seed for the learned-speed state -----------------------------------
# A host packed on minutes it measured itself predicts itself, so a leg
# calibration can only read speed from groups that moved class between runs
# (plan review, link#259). Few did, so the same calibration on 10-23 mostly
# reads the two classes' different drift, and the state is seeded equal.
d <- test[!test$wsg %in% stalls, ]
sp23 <- leg_speed(d, m17[d$wsg])
moved <- sum(both$class17 != both$class23)
cat("## Seed\n\n")
cat(sprintf("Groups that moved class between the runs (stalls left out): %d of %d.\n", moved, nrow(both)))
cat(sprintf("The leg calibration on 10-23 (projected from 10-17 minutes at equal speeds) reads cloud %.3f of m1,",
            sp23[["cloud"]]))
cat(sprintf(paste0(" close to the ratio of the two classes' drift alone (%.3f / %.3f = %.3f),",
                   " so it measures drift, not speed.\n"),
            cross["m1 -> m1", "sum_ratio"], cross["cloud -> cloud", "sum_ratio"],
            cross["m1 -> m1", "sum_ratio"] / cross["cloud -> cloud", "sum_ratio"]))
cat("The learned-speed state is seeded equal: m1 1, cloud 1.\n")
