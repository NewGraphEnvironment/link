#' Render the config dictionaries as one markdown README
#'
#' Every `inst/extdata/configs/dictionary_*.csv` becomes one section with one
#' table, whose columns are that dictionary's own. The result is written to
#' `inst/extdata/configs/README.md` by `data-raw/dictionary_readme_build.R`,
#' and `test-dictionaries.R` holds the shipped file equal to this function's
#' output, so a dictionary edit without a rebuilt README fails the tests
#' (link#75).
#'
#' @param dir Directory holding the `dictionary_*.csv` files.
#' @return The README as one character string, ending in a newline.
#' @noRd
.lnk_dictionary_readme <- function(
    dir = system.file("extdata", "configs", package = "link")) {
  files <- sort(list.files(dir, pattern = "^dictionary_[a-z_]+\\.csv$",
                           full.names = TRUE), method = "radix")
  if (length(files) == 0L) {
    stop("no dictionary_*.csv in ", dir, call. = FALSE)
  }
  # One table cell. Outside code spans every character markdown could read as
  # syntax (emphasis, links, HTML, entities, strikethrough, the table's `|`) is
  # backslash-escaped, so `_river_` is not italic and `<stage>` is not a tag;
  # inside a code span only `|` is, which GFM tables need. A cell with an odd
  # number of backticks has no code span, so its backticks are escaped too.
  # test-dictionaries.R checks every cell against what cmark-gfm displays.
  cell <- function(x) {
    x <- ifelse(is.na(x), "", as.character(x))
    x <- gsub("\r?\n", " ", x)
    vapply(x, function(v) {
      if (!nzchar(v)) return(v)
      esc <- function(p) gsub("([\\[\\]\\\\*_<>&~|`])", "\\\\\\1", p, perl = TRUE)
      n_tick <- nchar(v) - nchar(gsub("`", "", v, fixed = TRUE))
      if (n_tick %% 2L == 1L) return(esc(v))
      parts <- strsplit(v, "`", fixed = TRUE)[[1]]
      # strsplit() drops a trailing empty field; put it back.
      if (endsWith(v, "`")) parts <- c(parts, "")
      prose <- seq_along(parts) %% 2L == 1L
      parts[prose] <- esc(parts[prose])
      parts[!prose] <- gsub("|", "\\|", parts[!prose], fixed = TRUE)
      paste(parts, collapse = "`")
    }, character(1), USE.NAMES = FALSE)
  }
  out <- c(
    "# Config column dictionaries",
    "",
    paste("<!-- Generated by data-raw/dictionary_readme_build.R from the",
          "dictionary_*.csv files beside it. Do not edit by hand. -->"),
    "",
    paste("Each section documents the columns of one bundle file, from",
          "`dictionary_<file>.csv` in this directory. The CSV is the source;",
          "this page is rendered from it."),
    ""
  )
  for (f in files) {
    # UTF-8 whatever the locale: the README is compared with a UTF-8 read.
    d <- utils::read.csv(f, check.names = FALSE, colClasses = "character",
                         na.strings = character(), encoding = "UTF-8")
    target <- sub("^dictionary_(.*)\\.csv$", "\\1", basename(f))
    out <- c(
      out,
      paste0("## `", target, "`"),
      "",
      paste0("From `", basename(f), "`: ", nrow(d), " columns."),
      "",
      paste0("| ", paste(names(d), collapse = " | "), " |"),
      paste0("|", paste(rep("---", ncol(d)), collapse = "|"), "|"),
      apply(d, 1L, function(r) {
        paste0("| ", paste(cell(r), collapse = " | "), " |")
      }),
      ""
    )
  }
  paste0(paste(out[-length(out)], collapse = "\n"), "\n")
}
